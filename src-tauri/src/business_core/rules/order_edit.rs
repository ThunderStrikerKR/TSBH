//! Authoritative editable-order state transitions, selected client, and
//! client-specific freight. No GUI or persistence side effects.
//! Previous TypeScript baselines: useOrderDesk.tsx::edit, domain.ts::orderClient,
//! useAppModel.ts::saveOrder freight, OrderDesk.tsx::onDealer.
use serde_json::{json,Value};
use super::{field,flag,has_value,req,required_str,rows,set,str_field};

fn company_party(settings:&Value)->Value {
    // Exactly order-types.ts::companyParty, including empty company client ID.
    json!({
        "postcode":field(settings,"senderPostcode").as_str().unwrap_or(""),
        "id":"","name":"반도스탠드",
        "address":field(settings,"senderAddress").as_str().unwrap_or(""),
        "phone":field(settings,"senderPhone").as_str().unwrap_or(""),
        "mobile":field(settings,"senderMobile").as_str().unwrap_or(""),
        "contact":"","tier":"retail","payment":"POSTPAID",
        "shippingFeeExcluded":false,"active":true,
        "identifiers":"","overrides":{}
    })
}
pub(super) fn client(order:&Value,state:&Value)->Value {
    if str_field(order,"orderType")=="RETAIL" {
        return order.get("clientSnapshot").filter(|v|!v.is_null())
            .cloned().unwrap_or_else(||company_party(field(state,"settings")));
    }
    if (has_value(field(order,"confirmedAt")) || flag(order,"pricesLocked")) &&
       has_value(field(order,"clientSnapshot")) {
        return field(order,"clientSnapshot").clone();
    }
    rows(field(state,"clients")).iter()
        .find(|c|str_field(c,"id")==str_field(order,"clientId"))
        .cloned()
        .or_else(||order.get("clientSnapshot").filter(|v|!v.is_null()).cloned())
        .unwrap_or(Value::Null)
}
fn live_client(order:&Value,state:&Value)->Value{
    rows(field(state,"clients")).iter()
        .find(|c|str_field(c,"id")==str_field(order,"clientId") &&
            !has_value(field(c,"deletedAt")))
        .cloned().unwrap_or_else(||client(order,state))
}
fn editable(order:&Value,state:&Value)->Result<(),String>{
    if has_value(field(order,"deletedAt")) {
        return Err("삭제된 발주는 이력으로만 조회할 수 있습니다.".into());
    }
    if str_field(order,"status")=="EXPORTED" ||
        rows(field(field(state,"workflow"),"shipments")).iter().any(|ship|
            str_field(ship,"orderId")==str_field(order,"id") &&
            flag(ship,"transferred") && !flag(ship,"legacyArchived")) {
        return Err("공장 전달 완료 주문은 변경할 수 없습니다. 출고 취소 / 회수 확인이 필요합니다.".into());
    }
    Ok(())
}
fn reset_edit(order:&mut Value,state:&Value,reason:&str,now:&str,
    recalculate_shipping:bool)->Result<(),String>{
    // This intent is generated by React; all decisions are made here, not
    // by the component that owns the text field.
    if flag(order,"pricesLocked") &&
        !has_value(field(order,"pendingBillingSnapshot")) &&
        !rows(field(field(state,"workflow"),"shipments")).iter().any(|ship|
            str_field(ship,"orderId")==str_field(order,"id") &&
            !flag(ship,"legacyArchived")) {
        set(order,"pendingBillingSnapshot",json!({"at":now,"reason":reason}))?;
    }
    let selected=live_client(order,state);
    if !selected.is_null(){set(order,"clientSnapshot",selected)?;}
    for (key,value) in [("pricesLocked",json!(false)),
        ("notified",json!(false)),("paid",json!(false)),
        ("postpaidApproved",json!(false)),("status",json!("REVIEW"))] {
        set(order,key,value)?;
    }
    if !str_field(order,"orderType").is_empty() {
        for row in order["recipients"].as_array_mut()
            .ok_or("수취인 목록을 확인하세요.")? {
            if !has_value(field(row,"dispatchOrigin")) {
                set(row,"dispatchOrigin",json!("FACTORY"))?;
            }
            let origin=field(row,"dispatchOrigin").clone();
            for item in row["items"].as_array_mut()
                .ok_or("상품 목록을 확인하세요.")? {
                set(item,"origin",origin.clone())?;
            }
        }
    }
    set(order,"updatedAt",json!(now))?;
    if recalculate_shipping {
        set(order,"shippingMode",json!("AUTO"))?;
        set(order,"shippingFee",Value::Null)?;
        set(order,"shippingVersion",json!(""))?;
    }
    Ok(())
}
fn prepare_edit(payload:&Value)->Result<Value,String>{
    let mut order=req(payload,"order")?.clone();
    let state=req(payload,"state")?;
    editable(&order,state)?;
    let marker=req(&order,"pendingNativeEdit")?;
    let reason=required_str(marker,"reason")?.to_string();
    let now=required_str(marker,"at")?.to_string();
    let recalculate=flag(marker,"recalculateShipping");
    reset_edit(&mut order,state,&reason,&now,recalculate)?;
    order.as_object_mut().ok_or("주문 데이터 형식 오류")?.remove("pendingNativeEdit");
    Ok(json!({"order":order}))
}
fn effective_shipping(order:&Value,state:&Value)->Result<Value,String>{
    let recommended=super::shipping::recommend(order,state)?;
    let selected=live_client(order,state);
    let waived=flag(&selected,"shippingFeeExcluded");
    let total=if waived {json!(0)}else{field(&recommended,"total").clone()};
    Ok(json!({"total":total,"version":field(&recommended,"version"),
        "waived":waived}))
}
fn prepare_save(payload:&Value)->Result<Value,String>{
    let state=req(payload,"state")?;
    let mut order=req(payload,"order")?.clone();
    if has_value(field(&order,"pendingNativeEdit")){
        return Err("주문 수정의 Rust 검증이 완료된 후 저장하세요.".into());
    }
    let selected=client(&order,state);
    if selected.is_null() || str_field(&selected,"id").is_empty(){
        return Err("거래처를 선택하세요.".into());
    }
    if str_field(&order,"shippingMode")=="AUTO" &&
        str_field(&order,"shippingVersion").is_empty() &&
        field(&order,"shippingFee").is_null() {
        let freight=effective_shipping(&order,state)?;
        set(&mut order,"shippingFee",field(&freight,"total").clone())?;
        set(&mut order,"shippingVersion",field(&freight,"version").clone())?;
    }
    Ok(json!({"order":order,"client":selected}))
}
// Dealer changes explicitly reprice even when the existing order has a
// confirmation timestamp: the original nativeRepriceEditedOrder used to
// quote every configured product regardless of confirmedAt. The passive
// reprice_order reducer correctly refuses frozen orders and must stay intact.
fn reprice_for_new_dealer(order:&mut Value,state:&Value,selected:&Value)->Result<(),String>{
    for recipient in order["recipients"].as_array_mut().ok_or("수취인 목록 오류")?{
        for item in recipient["items"].as_array_mut().ok_or("상품 목록 오류")?{
            let pid=str_field(item,"productId").to_owned();
            let vid=str_field(item,"variantId").to_owned();
            if vid.is_empty(){continue;}
            let product=rows(field(state,"products")).iter()
                .find(|p|str_field(p,"id")==pid);
            if let Some(product)=product{
                let quote=super::pricing::resolve_unit_price(product,&vid,selected)?;
                set(item,"unitPrice",quote)?;
                if flag(field(item,"modelProposal"),"required"){
                    if let Some(variant)=rows(field(product,"variants")).iter()
                        .find(|v|str_field(v,"id")==vid){
                        if !str_field(variant,"url").is_empty(){
                            set(item,"url",field(variant,"url").clone())?;
                        }
                    }
                }
            }
        }
    }
    Ok(())
}
fn change_client(payload:&Value)->Result<Value,String>{
    let state=req(payload,"state")?;
    let before=req(payload,"order")?;
    let dealer_id=required_str(payload,"dealerId")?;
    let now=required_str(payload,"now")?;
    if str_field(before,"clientId")==dealer_id {return Ok(json!({"order":before}));}
    editable(before,state)?;
    if has_value(field(before,"pendingNativeEdit")){
        return Err("주문 수정의 Rust 검증이 완료된 후 거래처를 변경하세요.".into());
    }
    let issue=super::client_change::check(&json!({
        "state":state,"order":before,"dealerId":dealer_id
    }))?;
    if let Some(message)=field(&issue,"issue").as_str(){
        return Err(message.to_string());
    }
    let selected=rows(field(state,"clients")).iter()
        .find(|c|str_field(c,"id")==dealer_id && !has_value(field(c,"deletedAt")))
        .ok_or("변경할 거래처를 확인하세요.")?.clone();
    // Freeze the ORIGINAL order before selecting new dealer prices.
    let historical=if flag(before,"pricesLocked"){
        Some(super::reply_rules::billing(before,state,"거래처 변경",now)?)
    }else{None};
    let mut changed=before.clone();
    set(&mut changed,"clientId",json!(dealer_id))?;
    set(&mut changed,"clientSnapshot",selected.clone())?;
    // Preserve dealer-change provenance for audit, not as an extra review task.
    // An automatic claim must refer to the very client Rust is selecting.
    let match_info=field(payload,"matchEvidence");
    let guidance=if match_info.is_object(){
        let source=str_field(match_info,"source");
        let id=str_field(match_info,"clientId");
        let detail=str_field(match_info,"detail");
        if !["KAKAO_REMEMBERED","KAKAO_TITLE","RAW_EXPLICIT"].contains(&source)
            ||id!=dealer_id ||detail.trim().is_empty() ||detail.chars().count()>300 {
            return Err("거래처 자동 연결 근거가 현재 선택한 거래처와 일치하지 않습니다.".into());
        }
        json!({"source":source,"clientId":dealer_id,"detail":detail,
            "chatTitle":match_info.get("chatTitle").cloned().unwrap_or(Value::Null),
            "confirmedMatchCount":match_info.get("confirmedMatchCount").cloned().unwrap_or(Value::Null)})
    }else{
        json!({"source":"MANUAL","clientId":dealer_id,
            "detail":format!("사용자가 거래처 ‘{}’를 직접 선택했습니다.",str_field(&selected,"name"))})
    };
    set(&mut changed,"clientMatch",guidance)?;
    for (key,value) in [("pricesLocked",json!(false)),
        ("notified",json!(false)),("paid",json!(false)),
        ("postpaidApproved",json!(false)),("status",json!("REVIEW")),
        ("updatedAt",json!(now))]{
        set(&mut changed,key,value)?;
    }
    reprice_for_new_dealer(&mut changed,state,&selected)?;
    if let Some(snapshot)=historical{
        let mut history=rows(field(&changed,"billingHistory")).to_vec();
        history.push(snapshot);
        set(&mut changed,"billingHistory",json!(history))?;
    }
    // A changed dealer may change freight waivers AND applicable tariffs.
    // Quote before returning to React, so an immediate workflow save never
    // persists the previous dealer's freight or an unconfirmed null marker.
    set(&mut changed,"shippingMode",json!("AUTO"))?;
    let freight=effective_shipping(&changed,state)?;
    set(&mut changed,"shippingFee",field(&freight,"total").clone())?;
    set(&mut changed,"shippingVersion",field(&freight,"version").clone())?;
    Ok(json!({"order":changed}))
}
/// Apply an explicitly addressed edit to an existing operational order.
/// Never turn a confirmed order into a draft or rewrite its first receipt.
/// Existing shipment reconciliation owns stage rechecks and immutable audit.
fn change_confirmed_dispatch_origin(payload:&Value)->Result<Value,String>{
    let before=req(payload,"state")?;
    let shipment_id=required_str(payload,"shipmentId")?;
    let group_id=required_str(payload,"groupId")?;
    let origin=required_str(payload,"origin")?;
    let now=required_str(payload,"now")?;
    let seed=required_str(payload,"eventSeed")?;
    if !matches!(origin,"FACTORY"|"STORE"){
        return Err("발송지는 공장 또는 매장만 선택할 수 있습니다.".into());
    }
    let ship=rows(field(field(before,"workflow"),"shipments")).iter()
        .find(|ship|str_field(ship,"id")==shipment_id &&
            str_field(ship,"groupId")==group_id &&
            !flag(ship,"transferred") && !flag(ship,"legacyArchived"))
        .ok_or("수정할 배송 건을 확인하세요.")?;
    let oi=rows(field(before,"orders")).iter()
        .position(|order|str_field(order,"id")==str_field(ship,"orderId"))
        .ok_or("배송 건의 주문을 찾을 수 없습니다.")?;
    let order=&before["orders"][oi];
    editable(order,before)?;
    if !has_value(field(order,"confirmedAt")){
        return Err("확정된 주문을 선택하세요.".into());
    }
    let ri=rows(field(order,"recipients")).iter()
        .position(|row|str_field(row,"id")==str_field(ship,"recipientId"))
        .ok_or("배송 건의 수취인을 찾을 수 없습니다.")?;
    let previous=&order["recipients"][ri];
    if str_field(previous,"dispatchOrigin")==origin &&
        rows(field(previous,"items")).iter().all(|item|str_field(item,"origin")==origin){
        return Ok(json!({"state":before,"unchanged":true}));
    }
    let mut state=before.clone();
    let mut recipient=previous.clone();
    set(&mut recipient,"dispatchOrigin",json!(origin))?;
    for item in recipient["items"].as_array_mut().ok_or("상품 목록 오류")?{
        set(item,"origin",json!(origin))?;
    }
    // Freight is origin-specific. Keep a known charge for the selected
    // origin only when it was already in this shipment; never copy a factory
    // charge to the store (or vice versa). A new origin needs verification.
    let existing=if rows(field(previous,"items")).iter().any(|item|str_field(item,"origin")==origin){
        field(field(ship,"charges"),origin).clone()
    }else{Value::Null};
    let mut charges=serde_json::Map::new();
    charges.insert(origin.to_owned(),existing);
    set(&mut recipient,"shippingCharges",Value::Object(charges))?;
    let audit=json!({
        "id":format!("{seed}:confirmed-origin"),"at":now,
        "actor":field(field(before,"settings"),"operatorName").as_str()
            .filter(|name|!name.trim().is_empty()).unwrap_or("직원"),
        "action":"발송지 변경","shipmentIds":[shipment_id],"groupId":group_id,
        "before":{"dispatchOrigin":field(previous,"dispatchOrigin"),
            "itemOrigins":rows(field(previous,"items")).iter().map(|item|json!({
                "id":field(item,"id"),"origin":field(item,"origin")
            })).collect::<Vec<_>>(),"charges":field(ship,"charges")},
        "after":{"dispatchOrigin":origin,"charges":field(&recipient,"shippingCharges")}
    });
    state["workflow"]["events"].as_array_mut().ok_or("업무 이벤트 목록 누락")?.push(audit);
    state["orders"][oi]["recipients"][ri]=recipient;
    set(&mut state["orders"][oi],"updatedAt",json!(now))?;
    // Scoped reconciliation changes only this source order and its split
    // groups; validation below still sees the full operational before-image.
    let result=super::reconciliation::reconcile_shipment(&json!({
        "state":state,"shipmentId":shipment_id,"groupId":group_id,
        "now":now,"eventSeed":seed
    }))?;
    let changed=req(&result,"state")?;
    super::validation::validate_reception(before,changed)?;
    super::validate_workflow_transition(changed,before)?;
    Ok(result)
}

pub(super) fn execute(payload:&Value)->Result<Value,String>{
    match required_str(payload,"action")? {
        "resolve_order_client" => Ok(json!({"client":client(req(payload,"order")?,
            req(payload,"state")?)})),
        "resolve_order_clients" => {
            let order=req(payload,"order")?;
            let state=req(payload,"state")?;
            Ok(json!({"client":client(order,state),"liveClient":live_client(order,state)}))
        },
        "change_confirmed_dispatch_origin" => change_confirmed_dispatch_origin(payload),
        "prepare_order_edit" => prepare_edit(payload),
        "calculate_order_shipping" => effective_shipping(req(payload,"order")?,
            req(payload,"state")?),
        "prepare_order_save" => prepare_save(payload),
        "change_order_client" => change_client(payload),
        action=>Err(format!("지원하지 않는 주문 편집 규칙: {action}"))
    }
}
#[cfg(test)]
mod tests{
    use super::*;
    fn setup()->Value{
        json!({"clients":[{"id":"c1","tier":"wholesale","shippingFeeExcluded":false},
            {"id":"c2","tier":"retail","shippingFeeExcluded":true}],
            "orders":[],"products":[],"workflow":{"shipments":[],"groups":[],"payments":[],"queue":[]}})
    }
    fn draft()->Value{
        json!({"id":"o1","clientId":"c1","orderType":"AGENCY",
            "recipients":[{"id":"r1","items":[]}],"pricesLocked":true,
            "paid":true,"notified":true,"postpaidApproved":true,
            "status":"STATEMENT","shippingFee":3000,"shippingMode":"AUTO",
            "shippingVersion":"old","clientSnapshot":{"id":"c1","tier":"wholesale"}})
    }
    #[test]fn edit_resets_business_flags_and_preserves_first_invoice_intent(){
        let mut o=draft();
        o["pendingNativeEdit"]=json!({"at":"t1","reason":"주문 정보 수정",
            "recalculateShipping":true});
        let result=prepare_edit(&json!({"order":o,"state":setup()})).unwrap();
        let next=&result["order"];
        assert_eq!(next["pricesLocked"],false);
        assert_eq!(next["notified"],false);
        assert_eq!(next["paid"],false);
        assert_eq!(next["postpaidApproved"],false);
        assert_eq!(next["status"],"REVIEW");
        assert_eq!(next["shippingFee"],Value::Null);
        assert_eq!(next["shippingVersion"],"");
        assert_eq!(next["pendingBillingSnapshot"]["at"],"t1");
        assert_eq!(next["recipients"][0]["dispatchOrigin"],"FACTORY");
        assert!(next.get("pendingNativeEdit").is_none());
    }
    #[test]fn edited_shipping_waiver_is_native_and_client_selection_respects_snapshot(){
        let mut state=setup();
        let mut o=draft();
        o["clientId"]=json!("c2");
        o["pricesLocked"]=json!(false);
        assert_eq!(client(&o,&state)["id"],"c2");
        assert_eq!(live_client(&o,&state)["shippingFeeExcluded"],true);
        assert_eq!(client(&draft(),&state)["id"],"c1");
        state["clients"][1]["deletedAt"]=json!("today");
        // The legacy client fallback permits the existing deleted master
        // record for a draft until its dealer is explicitly changed.
        assert_eq!(live_client(&o,&state)["id"],"c2");
    }
    #[test]fn live_client_projection_uses_master_for_pricing_and_snapshot_for_display(){
        let mut state=setup();
        let mut o=draft();
        o["confirmedAt"]=json!("2026-11-19T00:00:00Z");
        let value=execute(&json!({"action":"resolve_order_clients","order":o,"state":state})).unwrap();
        assert_eq!(value["client"]["tier"],"wholesale");
        assert_eq!(value["liveClient"]["tier"],"wholesale");
        state["clients"][0]["tier"]=json!("special");
        let value=execute(&json!({"action":"resolve_order_clients","order":o,"state":state})).unwrap();
        assert_eq!(value["client"]["tier"],"wholesale");
        assert_eq!(value["liveClient"]["tier"],"special");
        state["clients"][0]["deletedAt"]=json!("today");
        let value=execute(&json!({"action":"resolve_order_clients","order":o,"state":state})).unwrap();
        assert_eq!(value["liveClient"]["tier"],"wholesale");
    }
    #[test]fn retail_client_projection_keeps_company_identity(){
        let mut o=draft();
        o["orderType"]=json!("RETAIL");
        o["clientId"]=json!("");
        o["clientSnapshot"]=Value::Null;
        let value=execute(&json!({"action":"resolve_order_clients","order":o,"state":setup()})).unwrap();
        assert_eq!(value["client"]["name"],"반도스탠드");
        assert_eq!(value["liveClient"]["name"],"반도스탠드");
    }
    #[test]fn pending_native_edits_cannot_be_prepared_for_persistence(){
        let mut order=draft();
        order["pendingNativeEdit"]=json!({"at":"t","reason":"x","recalculateShipping":false});
        assert!(prepare_save(&json!({"order":order,"state":setup()})).is_err());
    }
}
