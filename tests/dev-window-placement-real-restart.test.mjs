import assert from "node:assert/strict";
import test from "node:test";
import {readFileSync} from "node:fs";
const read = p => readFileSync(new URL("../"+p, import.meta.url),"utf8");
test("DEV CI tests actual native window state across three EXE launches",()=>{
 const native=read("scripts/verify-dev-window-placement-win.ps1");
 const smoke=read("scripts/migration32-dev-windows-smoke.ps1");
 const workflow=read(".github/workflows/dev-windows-smoke.yml");
 assert.match(native,/ExistingProcessId/);
 assert.match(native,/GetWindowRect/);
 assert.match(native,/SetWindowPos/);
 assert.match(native,/WM_CLOSE|0x0010/);
 assert.match(native,/Close-Gracefully \$first/);
 assert.match(native,/\$second=Start-Again/);
 assert.match(native,/Close-Gracefully \$second/);
 assert.match(native,/\$third=Start-Again/);
 assert.match(native,/IsZoomed/);
 assert.match(native,/window-state-developer\.json/);
 assert.match(native,/window-state\.json/);
 assert.match(native,/DEV_WINDOW_RESTART_PASS/);
 assert.match(native,/DEV_WINDOW_PRODUCTION_ISOLATION/);
 assert.match(smoke,/verify-dev-window-placement-win\.ps1/);
 assert.match(smoke,/ExistingProcessId \$native\[0\]\.Id/);
 assert.ok(workflow.includes("scripts/verify-dev-window-placement-win.ps1"));
});
